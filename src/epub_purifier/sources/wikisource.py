"""Wikisource: public-domain texts exported to EPUB by Wikimedia's WS Export.

Search uses the MediaWiki API, and downloads go through WS Export, the tool the
Wikimedia community runs to build EPUB/PDF files from wiki pages. Both are
public, documented interfaces: no HTML page is scraped and no on-wiki text is
rewritten. Wikisource hosts public-domain and freely licensed works, so the EPUB
may be fetched, scanned and cleaned like any other download.
"""

from __future__ import annotations

import json
import re
import time
import urllib.parse

from .base import (
    BookListing,
    DownloadRefused,
    DownloadResult,
    MinInterval,
    SourceError,
    normalize_query,
)
from .net import fetch_bytes, looks_like_zip

BASE = "https://en.wikisource.org"
API = f"{BASE}/w/api.php"
EXPORT = "https://ws-export.wmcloud.org/"
ALLOWED_HOSTS = ("wikisource.org", "wmcloud.org")

MAX_API_BYTES = 2 * 1024 * 1024
MAX_EPUB_BYTES = 64 * 1024 * 1024

#: Wikimedia asks API clients to stay polite; one request a second is ample.
REQUEST_INTERVAL = 1.0
LANGUAGE = "en"

_PAGE_ID = re.compile(r"^[0-9]{1,12}$")
_UNSAFE_NAME = re.compile(r"[^A-Za-z0-9 ._-]+")
EPUB_TYPES = {"application/epub+zip", "application/zip", "application/octet-stream"}


class WikisourceSource:
    name = "wikisource"
    label = "Wikisource"
    supports_download = True
    note = (
        "Public-domain and freely licensed texts from the Wikimedia project. "
        "The EPUB is built on demand by Wikimedia's WS Export service, then "
        "scanned and cleaned here."
    )

    def __init__(
        self,
        *,
        fetch=fetch_bytes,
        interval: float = REQUEST_INTERVAL,
        sleep=time.sleep,
    ) -> None:
        self._fetch = fetch
        self._limiter = MinInterval(interval, sleep=sleep)

    # -- search ----------------------------------------------------------
    def search(self, query: str) -> list[BookListing]:
        query = normalize_query(query)
        params = {
            "action": "query",
            "list": "search",
            "srsearch": query,
            "srnamespace": "0",
            "srlimit": "20",
            "format": "json",
            "formatversion": "2",
        }
        payload = self._json(f"{API}?{urllib.parse.urlencode(params)}", what="search")
        pages = (payload.get("query") or {}).get("search") or []
        if not isinstance(pages, list):
            raise SourceError("Wikisource search returned an unexpected payload")

        listings: list[BookListing] = []
        for page in pages:
            if not isinstance(page, dict):
                continue
            page_id = page.get("pageid")
            title = str(page.get("title") or "").strip()
            if not isinstance(page_id, int) or page_id <= 0 or not title:
                continue
            listings.append(
                BookListing(
                    source=self.name,
                    source_label=self.label,
                    book_id=str(page_id),
                    title=title[:300],
                    formats=("EPUB",),
                    details_url=f"{BASE}/?curid={page_id}",
                    downloadable=True,
                    download_note=(
                        "EPUB is generated by Wikisource's export service when fetched."
                    ),
                )
            )
        return listings[:20]

    # -- download --------------------------------------------------------
    def download(self, book_id: str) -> DownloadResult:
        page_id = self._clean_id(book_id)
        page = self._page(page_id)
        title = str(page.get("title") or "").strip()
        params = {"lang": LANGUAGE, "format": "epub", "page": title}

        self._limiter.wait()
        fetched = self._fetch(
            f"{EXPORT}?{urllib.parse.urlencode(params)}",
            allowed_hosts=ALLOWED_HOSTS,
            timeout=60.0,
            max_bytes=MAX_EPUB_BYTES,
            accept="application/epub+zip",
        )
        if fetched.content_type not in EPUB_TYPES:
            raise SourceError(
                "Wikisource's export service returned a page instead of an EPUB",
                detail=fetched.content_type or "unknown",
            )
        if not looks_like_zip(fetched.data):
            raise SourceError("The exported file is not a ZIP archive")

        return DownloadResult(
            data=fetched.data,
            file_name=_safe_file_name(title, page_id),
            origin_url=fetched.url,
        )

    # -- internals -------------------------------------------------------
    def _page(self, page_id: str) -> dict:
        params = {
            "action": "query",
            "pageids": page_id,
            "prop": "info",
            "inprop": "url",
            "format": "json",
            "formatversion": "2",
        }
        payload = self._json(f"{API}?{urllib.parse.urlencode(params)}", what="page")
        pages = (payload.get("query") or {}).get("pages") or []
        page = pages[0] if pages and isinstance(pages[0], dict) else None
        if page is None or page.get("missing"):
            raise DownloadRefused(
                "Wikisource has no page with that identifier", detail=page_id
            )
        return page

    def _json(self, url: str, *, what: str) -> dict:
        self._limiter.wait()
        fetched = self._fetch(
            url,
            allowed_hosts=ALLOWED_HOSTS,
            timeout=20.0,
            max_bytes=MAX_API_BYTES,
            accept="application/json",
        )
        if "json" not in fetched.content_type:
            raise SourceError(
                f"Wikisource {what} returned an unexpected content type",
                detail=fetched.content_type or "unknown",
            )
        try:
            payload = json.loads(fetched.data.decode("utf-8"))
        except (UnicodeDecodeError, json.JSONDecodeError) as exc:
            raise SourceError(f"Wikisource {what} returned unreadable JSON") from exc
        if not isinstance(payload, dict):
            raise SourceError(f"Wikisource {what} returned an unexpected payload")
        return payload

    @staticmethod
    def _clean_id(book_id: str) -> str:
        candidate = str(book_id or "").strip()
        if not _PAGE_ID.match(candidate):
            raise DownloadRefused("That Wikisource identifier is not valid", detail=candidate[:40])
        return candidate


def _safe_file_name(title: str, page_id: str) -> str:
    slug = _UNSAFE_NAME.sub(" ", title).strip()
    slug = " ".join(slug.split())[:80].strip(" .")
    return f"{slug or f'wikisource-{page_id}'}.epub"


